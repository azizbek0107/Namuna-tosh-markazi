import { createServer } from 'node:http';
import { mkdtempSync, unlinkSync, rmdirSync, existsSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import test from 'node:test';
import assert from 'node:assert/strict';
import { authMiddleware } from './auth.js';

test('login, roles, credential changes, sessions and persistent accounts', async () => {
  const directory = mkdtempSync(join(tmpdir(), 'stonex-auth-'));
  const middleware = authMiddleware({ directory });
  const server = createServer((req, res) => middleware(req, res, () => { res.writeHead(200, { 'Content-Type': 'application/json' }); res.end('{"ok":true}'); }));
  await new Promise((resolve) => server.listen(0, '127.0.0.1', resolve));
  const origin = `http://127.0.0.1:${server.address().port}`;
  async function request(path, data, cookie, site = origin) {
    const response = await fetch(origin + '/api/' + path, { method: data ? 'POST' : 'GET', headers: { Origin: site, ...(cookie ? { Cookie: cookie } : {}), 'Content-Type': 'application/json' }, ...(data ? { body: JSON.stringify(data) } : {}) });
    return { status: response.status, body: await response.json(), cookie: response.headers.get('set-cookie')?.split(';')[0], header: response.headers.get('set-cookie') };
  }
  try {
    assert.equal((await request('auth/session')).body.setup, true);
    assert.equal((await request('revenue-analysis')).status, 401);
    assert.equal((await request('attendance')).status, 401);
    const admin = { name: 'Admin', login: 'admin', password: 'Admin-test-2468' };
    assert.equal((await request('auth/setup', admin, null, 'https://other.example')).status, 403);
    assert.equal((await request('auth/setup', admin)).status, 200);
    assert.equal((await request('auth/setup', admin)).status, 403);
    assert.equal((await request('auth/login', { ...admin, password: 'wrong' })).status, 401);
    const signed = await request('auth/login', admin);
    assert.equal(signed.body.user.role, 'admin');
    assert.match(signed.header, /HttpOnly/);
    assert.equal(signed.body.user.hash, undefined);
    assert.equal((await request('auth/users', null, signed.cookie)).status, 200);
    for (const role of ['worker', 'cashier']) {
      const credentials = { name: role, login: role, password: 'Role-test-2468', role };
      assert.equal((await request('auth/users', credentials, signed.cookie)).status, 200);
      const result = await request('auth/login', credentials);
      assert.equal(result.body.user.role, role);
      assert.equal((await request('auth/users', null, result.cookie)).status, 403);
      assert.equal((await request('auth/bonuses', null, result.cookie)).status, 403);
      assert.equal((await request('auth/attendance/mark', { employeeId: 'employee1', name: 'Test', day: '2020-01-01', status: 'present' }, result.cookie)).status, 403);
      assert.equal((await request('auth/bonuses', { employeeId: 'employee1', name: 'Test', day: '2026-10-20', amount: 50000 }, result.cookie)).status, 403);
      assert.equal((await request('auth/users', { ...admin, login: 'hacked', role: 'admin' }, result.cookie)).status, 403);
      assert.equal((await request('revenue-analysis', null, result.cookie)).status, 403);
      assert.equal((await request('auth/attendance', { action: 'leave' }, result.cookie)).status, 409);
      const arrived = await request('auth/attendance', { action: 'arrive', userId: signed.body.user.id }, result.cookie);
      assert.equal(arrived.status, 200);
      assert.equal(arrived.body.attendance[0].userId, result.body.user.id);
      assert.equal((await request('attendance', null, result.cookie)).body.attendance[0].id, arrived.body.attendance[0].id);
      assert.equal((await request('auth/attendance/update', { id: arrived.body.attendance[0].id, reason: 'test' }, result.cookie)).status, 403);
      assert.equal((await request('auth/attendance/cancel', { id: arrived.body.attendance[0].id, reason: 'test' }, result.cookie)).status, 403);
      const bare = await fetch(origin + '/attendance', { headers: { Cookie: result.cookie } });
      assert.equal(bare.status, 200);
      assert.equal((await request('auth/attendance', { action: 'arrive' }, result.cookie)).status, 409);
      assert.equal((await request('auth/attendance', null, result.cookie)).body.attendance.every((item) => item.userId === result.body.user.id), true);
      assert.equal((await request('auth/attendance', { action: 'leave' }, result.cookie)).status, 200);
      assert.equal((await request('auth/attendance', { action: 'arrive' }, result.cookie)).status, 409);
      assert.ok((await request('auth/attendance', null, signed.cookie)).body.attendance.some((item) => item.userId === result.body.user.id && item.leftAt));
      assert.equal((await request('auth/profile', { ...credentials, login: 'changed', current: 'wrong' }, result.cookie)).status, 403);
      assert.equal((await request('auth/logout', {}, result.cookie)).status, 200);
      assert.equal((await request('auth/session', null, result.cookie)).body.user, null);
    }
    assert.equal((await request('auth/profile', { name: 'Admin', login: 'admin2', password: 'New-test-2468', current: admin.password }, signed.cookie)).status, 200);
    assert.equal((await request('auth/login', admin)).status, 401);
    assert.equal((await request('auth/login', { login: 'admin2', password: 'New-test-2468' })).status, 200);
    assert.equal((await request('auth/users', { name: 'Ishchi', login: 'badrole', password: 'Role-test-2468', role: 'owner' }, signed.cookie)).status, 400);
    const bonus = { employeeId: 'employee1', name: 'Test', day: '2026-10-20', amount: '50000', note: 'Kunlik bonus' };
    const mark = { employeeId: 'employee1', name: 'Test', day: '2020-01-01', status: 'absent' };
    assert.equal((await request('auth/attendance/mark', mark, signed.cookie)).status, 200);
    assert.equal((await request('auth/attendance/mark', { ...mark, status: 'present' }, signed.cookie)).status, 200);
    const marks = (await request('auth/attendance', null, signed.cookie)).body.marks;
    assert.equal(marks.length, 1);
    assert.equal(marks[0].status, 'present');
    assert.equal(marks[0].history[0].status, 'absent');
    assert.equal((await request('auth/attendance/mark', { ...mark, day: '2099-01-01' }, signed.cookie)).status, 400);
    assert.equal((await request('auth/bonuses', { ...bonus, amount: -1 }, signed.cookie)).status, 400);
    assert.equal((await request('auth/bonuses', { ...bonus, day: '2026-02-30' }, signed.cookie)).status, 400);
    assert.equal((await request('auth/bonuses', bonus, signed.cookie)).status, 200);
    assert.equal((await request('auth/bonuses', { ...bonus, amount: '60000' }, signed.cookie)).status, 200);
    const bonuses = (await request('auth/bonuses', null, signed.cookie)).body.bonuses;
    assert.equal(bonuses.length, 1);
    assert.equal(bonuses[0].amount, 60000);
    assert.equal(bonuses[0].history[1].amount, 50000);
    const listed = (await request('auth/users', null, signed.cookie)).body.users;
    const cashier = listed.find((item) => item.role === 'cashier');
    assert.equal(cashier.hash, undefined);
    const cashierSession = await request('auth/login', { login: 'cashier', password: 'Role-test-2468' });
    const change = { id: cashier.id, name: 'Yangi kassir', login: 'cashier2', role: 'cashier', password: '' };
    assert.equal((await request('auth/users/update', change, cashierSession.cookie)).status, 403);
    assert.equal((await request('auth/users/update', { ...change, login: 'worker' }, signed.cookie)).status, 400);
    assert.equal((await request('auth/users/update', { ...change, password: 'short' }, signed.cookie)).status, 400);
    assert.equal((await request('auth/users/update', { ...change, id: signed.body.user.id }, signed.cookie)).status, 404);
    assert.equal((await request('auth/users/update', change, signed.cookie)).status, 200);
    assert.equal((await request('auth/session', null, cashierSession.cookie)).body.user, null);
    assert.equal((await request('auth/login', { login: 'cashier', password: 'Role-test-2468' })).status, 401);
    assert.equal((await request('auth/login', { login: 'cashier2', password: 'Role-test-2468' })).body.user.id, cashier.id);
    assert.equal((await request('auth/users/update', { ...change, password: 'Changed-test-2468' }, signed.cookie)).status, 200);
    assert.equal((await request('auth/login', { login: 'cashier2', password: 'Role-test-2468' })).status, 401);
    assert.equal((await request('auth/login', { login: 'cashier2', password: 'Changed-test-2468' })).status, 200);
    const renewed = await request('auth/login', { login: 'cashier2', password: 'Changed-test-2468' });
    assert.equal((await request('auth/users/delete', { id: cashier.id }, renewed.cookie)).status, 403);
    assert.equal((await request('auth/users/delete', { id: signed.body.user.id }, signed.cookie)).status, 404);
    assert.equal((await request('auth/users/delete', { id: cashier.id }, signed.cookie)).status, 200);
    assert.equal((await request('auth/session', null, renewed.cookie)).body.user, null);
    assert.equal((await request('auth/login', { login: 'cashier2', password: 'Changed-test-2468' })).status, 401);
    assert.equal((await request('auth/users', null, signed.cookie)).body.users.some((item) => item.id === cashier.id), false);
    const saved = (await import('node:fs')).readFileSync(join(directory, 'users.json'), 'utf8');
    assert.equal(saved.includes('Changed-test-2468'), false);
    assert.equal(saved.includes('Role-test-2468'), false);
    const restored = authMiddleware({ directory });
    assert.equal(typeof restored, 'function');
    writeFileSync(join(directory, 'users.json'), '[]');
    const reset = await request('auth/session', null, signed.cookie);
    assert.equal(reset.body.user, null);
    assert.equal(reset.body.setup, true);
    assert.equal((await request('auth/login', { login: 'admin2', password: 'New-test-2468' })).status, 401);
    assert.equal((await request('auth/setup', { name: 'New owner', login: 'newowner', password: 'New-owner-2468' })).status, 200);
  } finally {
    await new Promise((resolve) => server.close(resolve));
    for (const name of ['users.json', 'users.json.tmp', 'attendance.json', 'attendance.json.tmp', 'bonuses.json', 'bonuses.json.tmp', 'attendance-marks.json', 'attendance-marks.json.tmp']) if (existsSync(join(directory, name))) unlinkSync(join(directory, name));
    rmdirSync(directory);
  }
});
